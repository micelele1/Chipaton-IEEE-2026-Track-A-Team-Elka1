`timescale 1ns/1ps

module SDES_tb;

    //------------------------------------------------------------
    // Inputs
    //------------------------------------------------------------

    reg         en;
    reg         encrypt;
    reg [0:9]   key;
    reg [0:7]   plaintext;

    //------------------------------------------------------------
    // Output
    //------------------------------------------------------------

    wire [0:7] ciphertext;

    //------------------------------------------------------------
    // Device Under Test
    //------------------------------------------------------------

    SDES dut (
        .en(en),
        .key(key),
        .plaintext(plaintext),
        .encrypt(encrypt),
        .ciphertext(ciphertext)
    );

    //------------------------------------------------------------
    // Task : Run Test
    //------------------------------------------------------------

    task run_test;

        input [0:7] pt;
        input [0:9] k;
        input enc;
        input [0:7] expected;

        begin

            plaintext = pt;
            key       = k;
            encrypt   = enc;
            en        = 1'b1;

            #10;

            $display("----------------------------------------");
            $display("PT  = %b",pt);
            $display("KEY = %b",k);

            if(enc)
                $display("MODE = ENCRYPT");
            else
                $display("MODE = DECRYPT");

            $display("OUT = %b",ciphertext);
            $display("EXP = %b",expected);

            if(ciphertext==expected)
                $display("PASS\n");
            else
                $display("FAIL\n");

        end

    endtask

    //------------------------------------------------------------
    // Test Sequence
    //------------------------------------------------------------

    initial begin

        $display("");
        $display("========================================");
        $display("      SDES Functional Verification");
        $display("========================================");
        $display("");

        //--------------------------------------------------------
        // Test Vector 1 (SageMath)
        //--------------------------------------------------------

        run_test(
            8'b01010101,
            10'b1010000010,
            1'b1,
            8'b11000001
        );

        //--------------------------------------------------------
        // Test Vector 2
        //--------------------------------------------------------

        run_test(
            8'b01000001,
            10'b1010000010,
            1'b1,
            8'b00010101
        );

        //--------------------------------------------------------
        // Disable Test
        //--------------------------------------------------------

        en = 1'b0;

        #10;

        $display("----------------------------------------");
        $display("Disable Test");
        $display("Ciphertext = %b",ciphertext);

        if(ciphertext==8'b00000000)
            $display("PASS\n");
        else
            $display("FAIL\n");

        //--------------------------------------------------------
        // Decryption Test
        //--------------------------------------------------------

        run_test(
            8'b11000001,
            10'b1010000010,
            1'b0,
            8'b01010101
        );

        //--------------------------------------------------------

        $display("========================================");
        $display("Simulation Finished");
        $display("========================================");

        $finish;

    end

endmodule